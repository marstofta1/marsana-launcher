'use strict';

const fs = require('fs');
const path = require('path');

const rootDir = path.join(__dirname, '..');
const src = path.join(rootDir, 'src', 'shared', 'bundledVersionManifest.json');
const outDir = path.join(rootDir, 'src', 'renderer', 'generated');
const out = path.join(outDir, 'versionManifest.js');

if (!fs.existsSync(src)) {
  console.error('bundledVersionManifest.json bulunamadi:', src);
  process.exit(1);
}

const data = JSON.parse(fs.readFileSync(src, 'utf8'));
if (!data || !Array.isArray(data.versions) || data.versions.length === 0) {
  console.error('Gecersiz bundledVersionManifest.json');
  process.exit(1);
}

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(
  out,
  `// Auto-generated by scripts/embed-version-manifest.js — do not edit.\nexport const BUNDLED_VERSION_MANIFEST = ${JSON.stringify(data)};\n`,
  'utf8'
);
console.log('Version manifest embedded:', data.versions.length, 'versions');
